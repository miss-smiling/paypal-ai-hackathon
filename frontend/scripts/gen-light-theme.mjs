// Generates app/light-theme.css from the Tailwind classes used in the code.
//
// The UI was written with dark colors only (bg-[#0a0e1e], text-white, border-slate-800...).
// Instead of adding dark: variants to every component, this script scans the source for
// those exact classes and emits overrides that apply when <html class="light">.
//
// Re-run it after adding new hardcoded dark classes:
//   node scripts/gen-light-theme.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const colors = require("tailwindcss/colors");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIRS = ["app", "components", "context", "lib"];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(name)) out.push(p);
  }
  return out;
}

// Collect every quoted-looking class token.
const tokens = new Set();
const tokenRe = /(?:[a-z-]+:)?(?:bg|text|border|from|via|to|ring)-(?:\[#[0-9a-fA-F]{3,8}\]|[a-z]+-\d{2,3}|white)(?:\/\d+)?/g;
for (const d of DIRS) {
  for (const f of walk(join(root, d))) {
    for (const m of readFileSync(f, "utf8").matchAll(tokenRe)) tokens.add(m[0]);
  }
}

const SLATE_TEXT = { 50: "#1e293b", 100: "#1e293b", 200: "#1e293b", 300: "#334155", 400: "#475569", 500: "#64748b", 600: "#64748b" };
const SLATE_BORDER = { 600: "#94a3b8", 700: "#cbd5e1", 800: "#e2e8f0", 900: "#e2e8f0" };
const SLATE_BG = { 950: "#f1f5f9", 900: "#ffffff", 800: "#e2e8f0", 700: "#cbd5e1", 600: "#94a3b8" };
const ACCENTS = ["cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose", "red",
  "orange", "amber", "yellow", "lime", "green", "emerald", "teal"];

function brightness(hex) {
  let h = hex.replace("#", "");
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.299 * r + 0.587 * g + 0.114 * b;
}

// Returns { prop, value } or null for a base token (no variant prefix).
function rule(base) {
  let m;
  if (base === "text-white") return ["color", "#0f172a"];
  if ((m = base.match(/^text-slate-(\d+)/))) return SLATE_TEXT[m[1]] ? ["color", SLATE_TEXT[m[1]]] : null;
  if ((m = base.match(/^text-([a-z]+)-(\d+)/)) && ACCENTS.includes(m[1]) && +m[2] >= 200 && +m[2] <= 400) {
    return ["color", colors[m[1]][700]];
  }
  if ((m = base.match(/^border-slate-(\d+)/))) return SLATE_BORDER[m[1]] ? ["border-color", SLATE_BORDER[m[1]]] : null;
  if (/^border-white/.test(base)) return ["border-color", "rgba(15,23,42,0.12)"];
  if ((m = base.match(/^bg-slate-(\d+)/))) return SLATE_BG[m[1]] ? ["background-color", SLATE_BG[m[1]]] : null;
  if ((m = base.match(/^bg-\[(#[0-9a-fA-F]{3,8})\]/))) {
    return ["background-color", brightness(m[1]) < 13 ? "#f1f5f9" : "#ffffff"];
  }
  if ((m = base.match(/^ring-\[(#[0-9a-fA-F]{3,8})\]/))) return ["--tw-ring-color", "#ffffff"];
  if ((m = base.match(/^from-\[(#[0-9a-fA-F]{3,8})\]/))) {
    return ["--tw-gradient-from", `${brightness(m[1]) < 13 ? "#f8fafc" : "#ffffff"} var(--tw-gradient-from-position)`];
  }
  if ((m = base.match(/^to-\[(#[0-9a-fA-F]{3,8})\]/))) {
    return ["--tw-gradient-to", `#f1f5f9 var(--tw-gradient-to-position)`];
  }
  if ((m = base.match(/^via-\[(#[0-9a-fA-F]{3,8})\]/))) {
    return ["--tw-gradient-stops", "var(--tw-gradient-from), #f8fafc var(--tw-gradient-via-position), var(--tw-gradient-to)"];
  }
  return null;
}

const out = [];
const skipped = new Set();
for (const tok of [...tokens].sort()) {
  const i = tok.lastIndexOf(":");
  const variant = i === -1 ? "" : tok.slice(0, i);
  const base = i === -1 ? tok : tok.slice(i + 1);
  const r = rule(base);
  if (!r) continue;
  const attr = `[class~="${tok}"]`;
  let sel;
  if (variant === "") sel = `html.light ${attr}`;
  else if (variant === "hover") sel = `html.light ${attr}:hover`;
  else if (variant === "focus") sel = `html.light ${attr}:focus`;
  else if (variant === "group-hover") sel = `html.light .group:hover ${attr}`;
  else { skipped.add(tok); continue; }
  out.push(`${sel} { ${r[0]}: ${r[1]}; }`);
}

const header = `/* GENERATED by scripts/gen-light-theme.mjs. Do not edit by hand.
   Light theme overrides for classes that were written dark-only. Active when <html class="light">. */

html.light { color-scheme: light; }
html.light body { background-color: #f1f5f9; color: #0f172a; }

/* Keep white text on solid colored buttons and badges */
html.light :is(.bg-blue-500, .bg-blue-600, .bg-blue-700, .bg-cyan-500, .bg-cyan-600, .bg-emerald-500,
  .bg-emerald-600, .bg-rose-500, .bg-rose-600, .bg-red-500, .bg-red-600, .bg-indigo-600, .bg-violet-600,
  .bg-purple-600, .bg-gradient-to-r:not([class*="from-[#"]), .bg-gradient-to-br:not([class*="from-[#"]),
  .bg-gradient-to-b:not([class*="from-[#"])).text-white,
html.light :is(.bg-blue-500, .bg-blue-600, .bg-blue-700, .bg-cyan-500, .bg-cyan-600, .bg-emerald-500,
  .bg-emerald-600, .bg-rose-500, .bg-rose-600, .bg-red-500, .bg-red-600, .bg-indigo-600, .bg-violet-600,
  .bg-purple-600, .bg-gradient-to-r:not([class*="from-[#"]), .bg-gradient-to-br:not([class*="from-[#"]),
  .bg-gradient-to-b:not([class*="from-[#"])) .text-white { color: #ffffff; }

html.light .glass-card { background: rgba(255, 255, 255, 0.8); border-color: rgba(15, 23, 42, 0.1); }
html.light .glass-card-hover:hover { background: #ffffff; }
html.light ::-webkit-scrollbar-track { background: #f1f5f9; }
html.light ::-webkit-scrollbar-thumb { background: #cbd5e1; }

`;
// The "keep white text" block must come last so it wins over the generic text-white rule.
const footer = header.split("/* Keep white text")[1];
const intro = header.split("/* Keep white text")[0];
const css = intro + out.join("\n") + "\n\n/* Keep white text" + footer;
writeFileSync(join(root, "app", "light-theme.css"), css);
console.log(`wrote app/light-theme.css with ${out.length} rules`);
if (skipped.size) console.log("skipped (unsupported variant):", [...skipped].join(", "));
